import { drizzle } from 'drizzle-orm/node-postgres';
import { migrate } from 'drizzle-orm/node-postgres/migrator';

const host = process.env.POSTGRES_HOST || '0.0.0.0';
const port = process.env.DATABASE_PORT || 5432;
const user = process.env.POSTGRES_USER;
const password = process.env.POSTGRES_PASSWORD;
const dbName = process.env.POSTGRES_DB;
const dbConnectionString = `postgresql://${user}:${password}@${host}:${port}/${dbName}`

export const db = drizzle(dbConnectionString);

export async function runMigrations() {
    console.log('Running database migrations...');
    console.log(dbConnectionString)

    // This reads the .sql files generated by drizzle-kit in your git repo
    await migrate(db, { migrationsFolder: './drizzle' });

    console.log('Migrations completed successfully');
}
